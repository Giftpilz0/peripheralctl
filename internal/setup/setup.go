// Package setup installs and removes peripheralctl for the current user. The
// udev rule is generated from the device tables and the systemd unit is
// embedded, so the binary is all a user needs.
package setup

import (
	"bytes"
	_ "embed"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"slices"
	"strings"

	"github.com/giftpilz0/peripheralctl/internal/config"
	"github.com/giftpilz0/peripheralctl/internal/razer"
	"github.com/giftpilz0/peripheralctl/internal/via"
)

//go:embed peripheralctl.service
var unitFile []byte

const (
	unitName = "peripheralctl.service"
	// The rule sets uaccess, which only takes effect on hotplug when it runs
	// before 73-seat-late.rules.
	rulePath = "/etc/udev/rules.d/70-peripheralctl.rules"
)

// keyboard is one USB product whose raw HID interface gets a rule.
type keyboard struct {
	vendor, product uint16
	iface           int
}

// ruleFile builds the udev rule. A mouse gets access by product. A keyboard
// gets its raw HID interface only, since its other interfaces carry keystrokes;
// the IDs and the interface sit on different parent devices, which takes two rules.
func ruleFile(razerProducts []uint16, keyboards []keyboard) []byte {
	var b strings.Builder
	b.WriteString("# Generated by 'peripheralctl install'.\n")
	ids := make([]string, len(razerProducts))
	for i, p := range razerProducts {
		ids[i] = fmt.Sprintf("%04x", p)
	}
	slices.Sort(ids)
	fmt.Fprintf(&b, "KERNEL==\"hidraw*\", SUBSYSTEM==\"hidraw\", ATTRS{idVendor}==\"1532\", ATTRS{idProduct}==\"%s\", TAG+=\"uaccess\"\n", strings.Join(ids, "|"))

	byInterface := map[int][]string{}
	for _, k := range keyboards {
		byInterface[k.iface] = append(byInterface[k.iface], fmt.Sprintf("0003:%04X:%04X.*", k.vendor, k.product))
	}
	ifaces := make([]int, 0, len(byInterface))
	for i := range byInterface {
		ifaces = append(ifaces, i)
	}
	slices.Sort(ifaces)
	for _, i := range ifaces {
		kernels := byInterface[i]
		slices.Sort(kernels)
		fmt.Fprintf(&b, "SUBSYSTEM==\"hidraw\", KERNELS==\"%s\", GOTO=\"peripheralctl_if%02x\"\n", strings.Join(kernels, "|"), i)
		fmt.Fprintf(&b, "GOTO=\"peripheralctl_if%02x_end\"\n", i)
		fmt.Fprintf(&b, "LABEL=\"peripheralctl_if%02x\"\n", i)
		fmt.Fprintf(&b, "ATTRS{bInterfaceNumber}==\"%02x\", TAG+=\"uaccess\"\n", i)
		fmt.Fprintf(&b, "LABEL=\"peripheralctl_if%02x_end\"\n", i)
	}
	return []byte(b.String())
}

// knownKeyboards lists built-in and imported keyboards. An imported one has to
// be connected for its raw HID interface to be known.
func knownKeyboards() []keyboard {
	var out []keyboard
	for _, d := range via.Builtin() {
		for _, p := range d.Products {
			out = append(out, keyboard{d.Vendor, p, d.RawInterface})
		}
	}
	imported, err := via.LoadDefinitions(config.KeyboardsDir())
	if err != nil {
		fmt.Printf("note: %v\n", err)
	}
	detected, _ := via.Detect()
	for _, d := range imported {
		for _, p := range d.Products {
			iface := -1
			for _, c := range detected {
				if c.Vendor == d.Vendor && c.Product == p {
					iface = c.Interface
				}
			}
			if iface < 0 {
				fmt.Printf("note: connect %s and run install again to give yourself access to it\n", d.Name)
				continue
			}
			out = append(out, keyboard{d.Vendor, p, iface})
		}
	}
	return out
}

func wantedRule() []byte { return ruleFile(razer.ProductIDs(), knownKeyboards()) }

// binPath is where the unit's ExecStart (%h/.local/bin/peripheralctl) expects us.
func binPath() string {
	home, _ := os.UserHomeDir()
	return filepath.Join(home, ".local", "bin", "peripheralctl")
}

func unitPath() string {
	dir := os.Getenv("XDG_CONFIG_HOME")
	if dir == "" {
		home, _ := os.UserHomeDir()
		dir = filepath.Join(home, ".config")
	}
	return filepath.Join(dir, "systemd", "user", unitName)
}

func step(format string, a ...any) { fmt.Printf("· "+format+"\n", a...) }

// run executes a command with the terminal attached (sudo may ask for a
// password).
func run(name string, args ...string) error {
	cmd := exec.Command(name, args...)
	cmd.Stdin, cmd.Stdout, cmd.Stderr = os.Stdin, os.Stdout, os.Stderr
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("%s %s: %w", name, strings.Join(args, " "), err)
	}
	return nil
}

func systemctl(args ...string) error { return run("systemctl", append([]string{"--user"}, args...)...) }

func notRoot() error {
	if os.Geteuid() == 0 {
		return errors.New("run this as your normal user, not with sudo: the service is per-user and sudo is asked for where needed")
	}
	return nil
}

func sameContent(path string, want []byte) bool {
	have, err := os.ReadFile(path)
	return err == nil && bytes.Equal(have, want)
}

// writeAtomic replaces path without ever leaving a partial file, which also
// works while the old binary is running.
func writeAtomic(path string, data []byte, perm fs.FileMode) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	tmp := path + ".new"
	if err := os.WriteFile(tmp, data, perm); err != nil {
		return err
	}
	if err := os.Chmod(tmp, perm); err != nil {
		_ = os.Remove(tmp)
		return err
	}
	return os.Rename(tmp, path)
}

// Install copies this binary to ~/.local/bin, installs the udev rule (via
// sudo, only if it changed) and enables the user service. It is safe to
// run again, e.g. to upgrade.
func Install() error {
	if err := notRoot(); err != nil {
		return err
	}
	self, err := os.Executable()
	if err != nil {
		return err
	}
	dst := binPath()
	if a, b := statOrNil(self), statOrNil(dst); a != nil && b != nil && os.SameFile(a, b) {
		step("binary already at %s", dst)
	} else {
		data, err := os.ReadFile(self)
		if err != nil {
			return err
		}
		if err := writeAtomic(dst, data, 0o755); err != nil {
			return err
		}
		step("installed binary to %s", dst)
	}

	rule := wantedRule()
	if sameContent(rulePath, rule) {
		step("udev rule %s up to date", rulePath)
	} else if err := installRule(rulePath, rule); err != nil {
		return err
	}

	if sameContent(unitPath(), unitFile) {
		step("service unit up to date")
	} else if err := writeAtomic(unitPath(), unitFile, 0o644); err != nil {
		return err
	} else {
		step("installed %s", unitPath())
	}
	for _, args := range [][]string{{"daemon-reload"}, {"enable", unitName}, {"restart", unitName}} {
		if err := systemctl(args...); err != nil {
			return err
		}
	}
	step("service enabled and (re)started")

	if !slices.Contains(filepath.SplitList(os.Getenv("PATH")), filepath.Dir(dst)) {
		fmt.Printf("note: %s is not in your PATH; add it to run 'peripheralctl' directly\n", filepath.Dir(dst))
	}
	fmt.Println("done: run 'peripheralctl' for the TUI, 'journalctl --user -u peripheralctl -f' for the service log")
	return nil
}

func statOrNil(path string) fs.FileInfo {
	st, _ := os.Stat(path)
	return st
}

func installRule(path string, data []byte) error {
	tmp, err := os.CreateTemp("", "peripheralctl-udev-*.rules")
	if err != nil {
		return err
	}
	defer func() { _ = os.Remove(tmp.Name()) }()
	if _, err := tmp.Write(data); err != nil {
		_ = tmp.Close()
		return err
	}
	_ = tmp.Close()
	step("installing udev rule %s (needs sudo)", path)
	if err := run("sudo", "install", "-m", "0644", tmp.Name(), path); err != nil {
		return err
	}
	return reloadUdev()
}

func reloadUdev() error {
	if err := run("sudo", "udevadm", "control", "--reload"); err != nil {
		return err
	}
	return run("sudo", "udevadm", "trigger", "--subsystem-match=hidraw", "--action=change")
}

// Uninstall stops and removes the service, the udev rule and the binary.
// The config is kept unless purge is set.
func Uninstall(purge bool) error {
	if err := notRoot(); err != nil {
		return err
	}
	var errs []error
	// Fails harmlessly if the unit is not installed.
	_ = exec.Command("systemctl", "--user", "disable", "--now", unitName).Run()
	if err := os.Remove(unitPath()); err == nil {
		step("removed %s", unitPath())
	} else if !errors.Is(err, fs.ErrNotExist) {
		errs = append(errs, err)
	}
	errs = append(errs, systemctl("daemon-reload"))

	if statOrNil(rulePath) != nil {
		step("removing udev rule %s (needs sudo)", rulePath)
		if err := run("sudo", "rm", "-f", rulePath); err != nil {
			errs = append(errs, err)
		} else {
			errs = append(errs, reloadUdev())
		}
	}

	if err := os.Remove(binPath()); err == nil {
		step("removed %s", binPath())
	} else if !errors.Is(err, fs.ErrNotExist) {
		errs = append(errs, err)
	}

	cfgDir := filepath.Dir(config.Path())
	if purge {
		if err := os.RemoveAll(cfgDir); err != nil {
			errs = append(errs, err)
		} else {
			step("removed %s", cfgDir)
		}
	} else if statOrNil(cfgDir) != nil {
		step("kept your settings in %s (use 'uninstall --purge' to remove them)", cfgDir)
	}
	if err := errors.Join(errs...); err != nil {
		return err
	}
	fmt.Println("peripheralctl uninstalled")
	return nil
}
